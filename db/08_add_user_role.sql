-- =====================================================================
-- [JWT] 회원 권한(role) 칸 추가 — 강의안 12주차 "users.role ADMIN|USER" (p.13)
--
-- 왜 필요한가?
--   예전 관리자 화면은 "관리자 비밀번호 + 세션"으로 잠갔다.
--   JWT 방식은 로그인 토큰 안에 role 을 담고, SecurityConfig 가 hasRole("ADMIN") 으로 막는다.
--   그래서 DB 에 "이 회원이 관리자인가"를 적어 둘 칸이 필요하다.
--
-- 실행: DBeaver 에서 passpace_merged 연결 → 이 파일 내용 붙여 넣기 → Alt+X
--       (여러 번 실행해도 안전: IF NOT EXISTS)
-- =====================================================================

ALTER TABLE USERS
  ADD COLUMN IF NOT EXISTS `role` VARCHAR(20) NOT NULL DEFAULT 'USER'
  COMMENT '권한: ADMIN 또는 USER (회원가입하면 항상 USER)';

